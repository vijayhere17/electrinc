
<?php

include '../includes/config.php';

header('Content-Type: application/json');

/*
|--------------------------------------------------------------------------
| PARTY ID
|--------------------------------------------------------------------------
*/

$party_id =
isset($_GET['party_id'])
? intval($_GET['party_id'])
: 0;

/*
|--------------------------------------------------------------------------
| FILTER
|--------------------------------------------------------------------------
*/

$filter_type =
isset($_GET['filter_type'])
? trim($_GET['filter_type'])
: 'All';

$data = [];

/*
|--------------------------------------------------------------------------
| QUERY
|--------------------------------------------------------------------------
*/

$sql = "

SELECT

    e.*,

    i.item_name as item_name

FROM entries e

LEFT JOIN items i
ON i.id = e.item_id

WHERE e.party_id = '$party_id'

";

/*
|--------------------------------------------------------------------------
| CASH/BILL FILTER
|--------------------------------------------------------------------------
*/

if($filter_type == 'Cash'){

    $sql .= " AND e.type_id = 1 ";

}
elseif($filter_type == 'Bill'){

    $sql .= " AND e.type_id = 2 ";
}

/*
|--------------------------------------------------------------------------
| ORDER
|--------------------------------------------------------------------------
*/

$sql .= "

ORDER BY e.id DESC

";

/*
|--------------------------------------------------------------------------
| EXECUTE
|--------------------------------------------------------------------------
*/

$result = $conn->query($sql);

if(!$result){

    echo json_encode([

        "entry_data" => []

    ]);

    exit;
}

/*
|--------------------------------------------------------------------------
| RESPONSE
|--------------------------------------------------------------------------
*/

while($row = $result->fetch_assoc()){

    /*
    |--------------------------------------------------------------------------
    | ENTRY TYPE
    |--------------------------------------------------------------------------
    */

    $entry_type = 'Cash';

    if($row['type_id'] == 2){

        $entry_type = 'Bill';
    }

    /*
    |--------------------------------------------------------------------------
    | ITEM NAME
    |--------------------------------------------------------------------------
    */

    $gold_silver = $row['item_name'];

    /*
    |--------------------------------------------------------------------------
    | CHECKED AMOUNT
    |--------------------------------------------------------------------------
    */

    $checked_amount =
    (float)$row['pending_qty']
    *
    (float)$row['rate'];

    /*
    |--------------------------------------------------------------------------
    | PUSH
    |--------------------------------------------------------------------------
    */

    $data[] = [

        "id" => (int)$row['id'],

        "rate" => (float)$row['rate'],

        "qty" => (float)$row['qty'],

        "pending_qty" => (float)$row['pending_qty'],

        "checked_amount" => $checked_amount,

        "mcx" => (float)$row['mcx'],

        "narration" => $row['narration'],

        "item_id" => (int)$row['item_id'],

        "type_id" => (int)$row['type_id'],

        "bill_cash" => $entry_type,

        "entry_type" => $entry_type,

        "gold_silver" => $gold_silver,

        "entry_date" => $row['entry_date'],

        "entry_date_new" => date(
            'd-m-Y',
            strtotime($row['entry_date'])
        ),

        "tds" => (float)$row['tds']

    ];
}

/*
|--------------------------------------------------------------------------
| FINAL RESPONSE
|--------------------------------------------------------------------------
*/

echo json_encode([

    "entry_data" => $data

]);

?>

